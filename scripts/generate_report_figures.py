"""Generate standardised report figures from committed data and outputs.

Every figure is written to ``report/figures`` as PNG at a consistent style.
Figures whose inputs are missing (for example, the market-making study
artifacts, which are generated by a heavier script) are skipped with a note.
The script is deterministic for figures computed from recorded values; the
C++ speedup figure measures a short local benchmark when the backend exists.
"""

