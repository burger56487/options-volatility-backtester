def hedging_sensitivity() -> None:
    source = (
        PROJECT_ROOT / "outputs" / "sensitivity"
        / "hedging_sensitivity_results.csv"
    )
    if not source.exists():
        print("skip hedging_sensitivity: file missing")
        return
    frame = pd.read_csv(source)
    grouped = frame.groupby("delta_threshold").agg(
        final_pnl=("final_pnl", "mean"),
        hedge_costs=("cumulative_hedge_costs", "mean"),
        hedge_trades=("number_of_hedge_trades", "mean"),
    )
    figure, axis = plt.subplots(figsize=(8.2, 4.8))
    axis.plot(grouped.index, grouped["final_pnl"], "o-", label="Mean final PnL")
    axis.set_xlabel("Delta hedge threshold")
    axis.set_ylabel("Mean final PnL", color="tab:blue")
    axis.tick_params(axis="y", labelcolor="tab:blue")
    twin = axis.twinx()
    twin.bar(grouped.index, grouped["hedge_costs"], alpha=0.35, color="tab:red", label="Mean hedge costs")
    twin.set_ylabel("Mean cumulative hedge costs", color="tab:red")
    twin.tick_params(axis="y", labelcolor="tab:red")
    lines, labels = axis.get_legend_handles_labels()
    lines2, labels2 = twin.get_legend_handles_labels()
    axis.legend(lines + lines2, labels + labels2, loc="best")
    axis.set_title("Hedging threshold sensitivity: PnL vs transaction costs")
    save(figure, "hedging_cost_sensitivity.png")


def var_backtest() -> None:
    price_path = PROJECT_ROOT / "data" / "raw" / "spy_daily_adjusted.csv"
    frame = pd.read_csv(price_path, parse_dates=["Date"]).set_index("Date")
    returns = frame["Close"].pct_change().dropna()
    rolling_var = (
        -returns.rolling(60)
        .apply(lambda x: np.quantile(x, 0.05), raw=True)
        .shift(1)
    )
    window = returns.iloc[60:]
    valid = pd.concat([window, rolling_var.loc[window.index]], axis=1).dropna()
    valid.columns = ["pnl", "var"]
    breaches = valid["pnl"] < -valid["var"]
    figure, axis = plt.subplots(figsize=(10.0, 4.6))
    axis.plot(valid.index, valid["pnl"], lw=0.5, label="Daily PnL")
    axis.plot(valid.index, -valid["var"], lw=1.0, color="tab:red", label="-95% VaR")
    axis.scatter(
        valid.index[breaches],
        valid["pnl"][breaches],
        s=18,
        color="black",
        label=f"Breaches ({int(breaches.sum())})",
        zorder=5,
    )
    axis.set_xlabel("Date")
    axis.set_ylabel("Daily return")
    axis.set_title("SPY 95% rolling historical VaR backtest (60-day window)")
    axis.legend()
    figure.autofmt_xdate()
    save(figure, "var_backtest_breaches.png")


def cpp_speedup() -> None:
    baseline_path = PROJECT_ROOT / "outputs" / "testing" / "benchmark_baseline.json"
    if not baseline_path.exists():
        print("skip cpp_speedup: benchmark_baseline.json missing")
        return
    baseline = json.loads(baseline_path.read_text(encoding="utf-8"))
    if not baseline.get("backend_available"):
        print("skip cpp_speedup: backend unavailable")
        return
    python_seconds = baseline["python_seconds"]
    cpp_seconds = baseline["cpp_seconds"]
    speedup = baseline["speedup"]
    figure, axis = plt.subplots(figsize=(6.8, 4.4))
    bars = axis.bar(
        ["Python scalar", "C++ batch"],
        [python_seconds, cpp_seconds],
        color=["tab:blue", "tab:green"],
    )
    axis.set_ylabel("Seconds (1,000,000 prices)")
    axis.set_title(f"C++ batch kernel vs Python scalar loop: {speedup:.1f}x")
    for bar, seconds in zip(bars, [python_seconds, cpp_seconds]):
        axis.text(
            bar.get_x() + bar.get_width() / 2,
            bar.get_height() * 1.02,
            f"{seconds:.3f}s",
            ha="center",
            va="bottom",
        )
    axis.set_ylim(0, python_seconds * 1.2)
    save(figure, "cpp_speedup.png")


def main() -> None:
    start = time.perf_counter()
    pricing_convergence()
    degeneracy_validation()
    svi_surface()
    backtest_figures()
    hedging_sensitivity()
    var_backtest()
    cpp_speedup()
    print(f"done in {time.perf_counter() - start:.1f}s")


if __name__ == "__main__":
    main()
